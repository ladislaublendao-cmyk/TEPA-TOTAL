  function normalize(code) {
    var raw = String(code || '').trim().toLowerCase();
    if (raw.indexOf('pt') === 0) return 'pt';
    if (raw.indexOf('en') === 0) return 'en';
    return '';
  }

  function detectInitialLang(cfg) {
    try {
      var params = new URLSearchParams(global.location ? global.location.search : '');
      var urlLang = normalize(params.get('lang'));
      if (urlLang) {
        saveLang(urlLang);
        return urlLang;
      }
    } catch (e) {}

    try {
      var stored = normalize(global.localStorage.getItem(STORAGE_KEY));
      if (stored) return stored;
    } catch (e) {}

    var wpLocale = normalize(cfg && cfg.wpLocale);
    if (wpLocale) return wpLocale;

    return 'en';
  }

  function saveLang(code) {
    var norm = normalize(code) || 'en';
    try {
      global.localStorage.setItem(STORAGE_KEY, norm);
    } catch (e) {}
    return norm;
  }

  function t(lang, key, vars) {
    var norm = normalize(lang) || 'en';
    var table = DICT[norm] || DICT.en;
    var str = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : (Object.prototype.hasOwnProperty.call(DICT.en, key) ? DICT.en[key] : key);

    if (vars && typeof str === 'string') {
      str = str.replace(/\{(\w+)\}/g, function (_, k) {
        return vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : '';
      });
    }
    return str;
  }

  function translateDom(lang, container) {
    if (!container || !container.querySelectorAll) return;
    container.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (key) el.textContent = t(lang, key);
    });
    container.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (key) el.setAttribute('placeholder', t(lang, key));
    });
    container.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-title');
      if (key) el.setAttribute('title', t(lang, key));
    });
  }

  global.TepaAdminI18n = {
    STORAGE_KEY: STORAGE_KEY,
    SUPPORTED: SUPPORTED,
    LANGUAGES: LANGUAGES,
    DICT: DICT,
    normalize: normalize,
    detectInitialLang: detectInitialLang,
    saveLang: saveLang,
    t: t,
    translateDom: translateDom
  };
